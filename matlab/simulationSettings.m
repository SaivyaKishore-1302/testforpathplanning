function [c,ok]=simulationSettings(c)
% Tabbed numeric configuration editor. Values are checked before acceptance.
ok=false; original=c;
spec={ ...
 'track','width','Track width (m)',2.1,15; ...
 'track','spacing','Cone spacing (m)',0.6,10; ...
 'track','scale','Circuit dimension multiplier',0.4,4; ...
 'track','sharpness','Corner sharpness',0,0.9; ...
 'track','closed','Closed circuit (0 or 1)',0,1; ...
 'track','targetCones','Total cone target (0 uses spacing)',0,1000; ...
 'track','irregularity','Spacing irregularity',0,0.7; ...
 'track','widthVariation','Width variation fraction',0,0.5; ...
 'track','missingBlue','Remove blue fraction',0,0.8; ...
 'track','missingYellow','Remove yellow fraction',0,0.8; ...
 'sensor','range','Detection range (m)',3,50; ...
 'sensor','fov','Field of view (radians)',0.3,2*pi; ...
 'sensor','frequency','Detection frequency (Hz)',1,100; ...
 'sensor','sigma','Base positional noise (m)',0,2; ...
 'sensor','distanceNoise','Noise increase (m per m)',0,0.1; ...
 'sensor','missRate','Missed detection probability',0,1; ...
 'sensor','colourAccuracy','Correct colour probability',0,1; ...
 'sensor','falseRate','Mean false detections per scan',0,20; ...
 'sensor','outageStart','Outage starts at (s; Inf disables)',0,inf; ...
 'sensor','outageDuration','Outage duration (s)',0,60; ...
 'localization','positionWalk','Position random walk (m / sqrt(s))',0,1; ...
 'localization','headingWalk','Heading walk (rad / sqrt(s))',0,0.3; ...
 'map','gate','Association radius (m)',0.1,3; ...
 'map','merge','Duplicate merge radius (m)',0.05,1; ...
 'map','ttl','Landmark lifetime (s)',0.2,300; ...
 'map','radius','Map retention radius (m)',5,100; ...
 'planner','frequency','Planning frequency (Hz)',1,100; ...
 'planner','minEdge','Minimum gate length (m)',0.2,10; ...
 'planner','maxEdge','Maximum gate length (m)',2,20; ...
 'planner','maxHeadingError','Gate heading tolerance (rad)',0.2,pi; ...
 'planner','maxTurn','Maximum midpoint turn (rad)',0.1,pi; ...
 'planner','maxGap','Maximum midpoint gap (m)',0.5,15; ...
 'planner','minLength','Minimum observed path (m)',0.5,15; ...
 'planner','beamWidth','Graph beam width',1,200; ...
 'planner','maxDepth','Graph search depth',2,100; ...
 'planner','ambiguityMargin','Ambiguity score fraction',0,0.8; ...
 'planner','smooth','Use validated cubic smoothing (0/1)',0,1; ...
 'planner','useWidth','Width filter (0/1)',0,1; ...
 'planner','useHeading','Heading filter (0/1)',0,1; ...
 'planner','useBoundary','Observed boundary filter (0/1)',0,1; ...
 'planner','useContinuity','Previous path continuity (0/1)',0,1; ...
 'vehicle','speed','Desired speed (m/s)',0.2,18; ...
 'vehicle','wheelbase','Wheelbase (m)',0.6,3; ...
 'vehicle','width','Vehicle width (m)',0.5,2; ...
 'vehicle','length','Vehicle length (m)',1,4; ...
 'vehicle','lookahead','Base lookahead (m)',0.8,10; ...
 'vehicle','lookaheadGain','Speed lookahead gain (s)',0,1; ...
 'vehicle','maxSteer','Maximum steering (rad)',0.1,1; ...
 'vehicle','steerRate','Steering slew rate (rad/s)',0.2,5; ...
 'vehicle','accel','Maximum acceleration (m/s^2)',0.2,8; ...
 'vehicle','brake','Braking deceleration (m/s^2)',0.5,12; ...
 'vehicle','lateralAccel','Corner lateral acceleration (m/s^2)',0.5,10; ...
 'vehicle','controlFrequency','Controller frequency (Hz)',1,200; ...
 'sim','dt','Integration timestep (s)',0.002,0.1; ...
 'sim','maxTime','Simulation time limit (s)',5,1800; ...
 'sim','stopOnCollision','Stop on collision (0/1)',0,1};
f=figure('Name','Simulation settings | SI units, angles in radians','NumberTitle','off', ...
    'Color','w','Position',[250 100 850 720],'WindowStyle','modal','CloseRequestFcn',@cancel);
tabs=uitabgroup(f,'Units','normalized','Position',[0.02 0.12 0.96 0.86]);
sections=unique(spec(:,1),'stable'); handles=cell(size(spec,1),1);
for j=1:numel(sections)
    tab=uitab(tabs,'Title',sections{j}); rows=find(strcmp(spec(:,1),sections{j}));
    for k=1:numel(rows)
        i=rows(k); y=0.94-(k-1)*0.055;
        uicontrol(tab,'Style','text','String',spec{i,3},'Units','normalized', ...
            'Position',[0.04 y 0.67 0.04],'BackgroundColor',get(tab,'BackgroundColor'), ...
            'HorizontalAlignment','left','FontSize',10);
        handles{i}=uicontrol(tab,'Style','edit','String',num2str(c.(spec{i,1}).(spec{i,2})), ...
            'Units','normalized','Position',[0.73 y 0.22 0.044],'BackgroundColor','w');
    end
end
uicontrol(f,'Style','text','String','Random seed','Units','normalized', ...
    'Position',[0.03 0.035 0.16 0.04],'BackgroundColor','w');
seed=uicontrol(f,'Style','edit','String',num2str(c.seed),'Units','normalized', ...
    'Position',[0.19 0.035 0.16 0.045],'BackgroundColor','w');
uicontrol(f,'Style','pushbutton','String','Apply and reset','Units','normalized', ...
    'Position',[0.66 0.025 0.29 0.06],'Callback',@apply);
uiwait(f); if isgraphics(f), delete(f); end
    function apply(~,~)
        proposed=original;
        for ii=1:size(spec,1)
            value=str2double(get(handles{ii},'String'));
            if isnan(value) || value<spec{ii,4} || value>spec{ii,5}
                errordlg(['Invalid value: ' spec{ii,3}]); return
            end
            flags={'closed','smooth','useWidth','useHeading','useBoundary','useContinuity','stopOnCollision'};
            if any(strcmp(spec{ii,2},flags)) && ~ismember(value,[0 1])
                errordlg(['Use 0 or 1: ' spec{ii,3}]); return
            end
            proposed.(spec{ii,1}).(spec{ii,2})=value;
        end
        value=str2double(get(seed,'String'));
        if ~isfinite(value) || value<0 || value>2^32-3 || value~=floor(value)
            errordlg('Seed must be a nonnegative integer below 2^32-2.'); return
        end
        proposed.seed=value;
        if proposed.planner.minEdge>=proposed.planner.maxEdge
            errordlg('Minimum gate length must be below maximum.'); return
        end
        if proposed.sim.dt>1/max([proposed.vehicle.controlFrequency,proposed.planner.frequency,proposed.sensor.frequency])+1e-9
            errordlg('Timestep must resolve the highest configured frequency.'); return
        end
        proposed.planner.beamWidth=round(proposed.planner.beamWidth);
        proposed.planner.maxDepth=round(proposed.planner.maxDepth);
        proposed.track.targetCones=round(proposed.track.targetCones);
        proposed.planner.width=proposed.track.width;
        c=proposed; ok=true; uiresume(f);
    end
    function cancel(~,~), c=original; uiresume(f); end
end
