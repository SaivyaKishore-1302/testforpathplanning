function result=summarizeRun(s)
L=s.log; e=s.evaluation; samples=e.reconstructionSamples;
result=struct('strategy',s.config.planner.strategy,'seed',s.config.seed, ...
    'success',e.complete && e.collisionCount==0 && e.violations==0, ...
    'lapComplete',e.complete,'laps',e.lap,'reason',s.reason,'elapsed',s.time, ...
    'distance',s.distance,'collisionCount',e.collisionCount, ...
    'collisionsPer100m',100*e.collisionCount/max(s.distance,eps),'boundaryViolations',e.violations, ...
    'meanReconstructionError',safeMean(samples),'maxReconstructionError',safeMax(samples), ...
    'rmsReconstructionError',sqrt(safeMean(samples.^2)), ...
    'meanCrossTrackError',safeMean(L(:,6)),'maxCrossTrackError',safeMax(L(:,6)), ...
    'meanPlanningMs',safeMean(L(:,10)),'validPlanRate',safeMean(L(:,11)), ...
    'validGateRate',safeMean(L(:,15)));
end
function v=safeMean(x)
x=x(isfinite(x)); if isempty(x), v=NaN; else, v=mean(x); end
end
function v=safeMax(x)
x=x(isfinite(x)); if isempty(x), v=NaN; else, v=max(x); end
end
